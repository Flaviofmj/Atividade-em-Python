# Solicita a altura da primeira pessoa
pessoa1 = float(input("Digite a altura de uma pessoa: "))

# Solicita a altura da segunda pessoa
pessoa2 = float(input("Digite a altura de outra pessoa: "))

# Verifica se a primeira pessoa é mais alta que a segunda
print("A altura da primeira pessoa é maior que a da segunda:", pessoa1 > pessoa2)

# Verifica se a primeira pessoa é mais baixa que a segunda
print("A altura da primeira pessoa é menor que a da segunda:", pessoa1 < pessoa2)

# Verifica se as duas pessoas possuem a mesma altura
print("A altura da primeira pessoa é igual à da segunda:", pessoa1 == pessoa2)

# Verifica se a primeira altura é maior ou igual à segunda
print("A altura da primeira pessoa é maior ou igual à da segunda:", pessoa1 >= pessoa2)

# Verifica se a primeira altura é menor ou igual à segunda
print("A altura da primeira pessoa é menor ou igual à da segunda:", pessoa1 <= pessoa2)

# Verifica se as duas alturas são diferentes
print("A altura da primeira pessoa é diferente da segunda:", pessoa1 != pessoa2)