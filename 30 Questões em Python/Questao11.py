# Declara duas variáveis com valores inteiros
numero1 = 100
numero2 = 15

# Calcula a soma dos dois números
soma = numero1 + numero2

# Calcula a subtração dos dois números
subtracao = numero1 - numero2

# Calcula a multiplicação dos dois números
multiplicacao = numero1 * numero2

# Calcula a divisão dos dois números
divisao = numero1 / numero2

# Exibe o resultado da soma
print("A soma de:", numero1, "+", numero2, "=", soma)

# Exibe o resultado da subtração
print("A subtração de:", numero1, "-", numero2, "=", subtracao)

# Exibe o resultado da multiplicação
print("A multiplicação de:", numero1, "*", numero2, "=", multiplicacao)

# Exibe o resultado da divisão com duas casas decimais
print(f"A divisão de: {numero1} / {numero2} = {divisao:.2f}")