numero1 = 15

# Declara a variável com o valor 15
numero2 = 15

# Exibe o primeiro número
print("Primeiro número:", numero1)

# Exibe o segundo número
print("Segundo número:", numero2)

# Verifica se o primeiro número é maior que o segundo
print("O primeiro número é maior que o segundo:", numero1 > numero2)

# Verifica se o primeiro número é menor que o segundo
print("O primeiro número é menor que o segundo:", numero1 < numero2)

# Verifica se os dois números são iguais
print("O primeiro número é igual ao segundo número:", numero1 == numero2)

# Verifica se os dois números são diferentes
print("O primeiro número é diferente do segundo número:", numero1 != numero2)

# Verifica se o primeiro número é maior ou igual ao segundo
print("O primeiro número é maior ou igual ao segundo número:", numero1 >= numero2)

# Verifica se o primeiro número é menor ou igual ao segundo
print("O primeiro número é menor ou igual ao segundo número:", numero1 <= numero2)