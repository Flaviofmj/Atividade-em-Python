# Solicita o tamanho da base do triângulo
base = float(input("Digite o tamanho da base: "))

# Solicita a altura do triângulo
altura = float(input("Digite a altura: "))

# Calcula a área do triângulo
# Fórmula: área = (base x altura) / 2
area = (base * altura) / 2

# Exibe o resultado da área calculada
print("A área total do triângulo é de:", area)