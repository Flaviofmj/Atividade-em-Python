# Solicita o primeiro número inteiro (dividendo)
numero1 = int(input("Digite um número: "))

# Solicita o segundo número inteiro (divisor)
numero2 = int(input("Digite outro número: "))

# Calcula o resto da divisão do primeiro número pelo segundo
resto = numero1 % numero2

# Exibe o dividendo
print("Dividendo:", numero1)

# Exibe o divisor
print("Divisor:", numero2)

# Exibe o resto da divisão
print("Resto da divisão:", resto)